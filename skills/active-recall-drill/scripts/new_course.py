#!/usr/bin/env python3
"""Scaffold a multi-chapter HTML course next to the material being studied.

Creates:

    <dir>/
      index.html             course map + progress
      ch01.html … chNN.html   one page per chapter
      assets/course.css       shared stylesheet
      assets/course.js        nav, progress, term rendering
      assets/course-data.js   chapter list (generated)
      assets/terms-data.js    term data for file:// (generated)
      术语.json                term source, empty by default

Pages open straight from disk (file://); no server and no reload polling.

Example:
    python3 scripts/new_course.py ~/notes/networking \
        --title "Networking Basics" \
        --chapters "Devices,Layer 2: VLAN,Layer 3: IP and gateway,Routing table"
"""

from __future__ import annotations

import argparse
import json
import shutil
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))  # allow loading as a module
import i18n  # noqa: E402  (local module, resolved after sys.path fix)

HERE = Path(__file__).resolve().parent
TEMPLATES = HERE.parent / "templates" / "course"

INDEX_NOTE = "按顺序上的课程：先看总图，再一章一章往下。"


def fill(template: str, mapping: dict[str, str]) -> str:
    out = template
    for key, value in mapping.items():
        out = out.replace("{{" + key + "}}", value)
    return out


def parse_chapters(raw: list[str]) -> list[tuple[str, str]]:
    chapters = []
    for item in raw:
        title, _, desc = item.partition("|")
        title = title.strip()
        if title:
            chapters.append((title, desc.strip()))
    return chapters


def build_data(chapters: list[tuple[str, str]], titles: list[str]) -> list[dict]:
    data = [{"num": "00", "id": "index", "title": "课程地图", "file": "index.html",
             "desc": "先看全局：这门课讲什么、按什么顺序学"}]
    for idx, ((title, desc), _) in enumerate(zip(chapters, titles), start=1):
        data.append({"num": f"{idx:02d}", "id": f"ch{idx:02d}", "title": title,
                     "file": f"ch{idx:02d}.html", "desc": desc})
    return data


def main() -> int:
    ap = argparse.ArgumentParser(description="Scaffold a multi-chapter HTML course.")
    ap.add_argument("dir", help="target directory (created if missing)")
    ap.add_argument("--title", required=True, help="course title")
    ap.add_argument("--chapters", required=True,
                    help="comma-separated chapter titles; 'Title|one-line description' is allowed")
    ap.add_argument("--kicker", default="", help="small line above the title")
    ap.add_argument("--lead", default="", help="one-sentence intro for the course map")
    ap.add_argument("--path", default="", help="optional one-line path diagram")
    ap.add_argument("--lang", choices=list(i18n.LANGS), help="page language; default follows the system locale")
    ap.add_argument("--force", action="store_true", help="overwrite an existing course directory")
    args = ap.parse_args()

    lang = i18n.detect(args.lang)
    target = Path(args.dir).expanduser().resolve()
    chapters = parse_chapters(args.chapters.split(","))
    if not chapters:
        print("no chapters given", file=sys.stderr)
        return 2
    if target.exists() and any(target.iterdir()) and not args.force:
        print(f"{target} is not empty; pass --force to overwrite", file=sys.stderr)
        return 1

    (target / "assets").mkdir(parents=True, exist_ok=True)
    for name in ("course.css", "course.js", "i18n.js", "notes-data.js"):
        shutil.copyfile(TEMPLATES / "assets" / name, target / "assets" / name)
    shutil.copyfile(TEMPLATES / "notes.html", target / "notes.html")

    index_tpl = (TEMPLATES / "index.html").read_text(encoding="utf-8")
    chapter_tpl = (TEMPLATES / "chapter.html").read_text(encoding="utf-8")

    data = build_data(chapters, [c[0] for c in chapters])
    (target / "assets" / "course-data.js").write_text(
        "// generated by new_course.py; edit the chapter list via the script or here\n"
        f'window.__COURSE_LANG = "{lang}";\n'
        "window.__COURSE_CHAPTERS = " + json.dumps(data, ensure_ascii=False) + ";\n" +
        "window.__COURSE_REFS = [];\n",
        encoding="utf-8")

    (target / "index.html").write_text(fill(index_tpl, {
        "TITLE": args.title,
        "NOTE": INDEX_NOTE,
        "KICKER": args.kicker,
        "LEAD": args.lead or "先建立一张总图，再一层一层往下钻。每章一页，页内分步演示。",
        "PATH": args.path or "（可选）在这里写这条主线的主干路径",
        "NOTE_BODY": "顺序是有依赖的：后面的章节默认你已经看过前面的。卡住就退回上一章。",
        "LANGATTR": "zh-CN" if lang == "zh" else "en",
    }), encoding="utf-8")

    for entry, (title, desc) in zip(data[1:], chapters):
        (target / entry["file"]).write_text(fill(chapter_tpl, {
            "NUM": entry["num"],
            "ID": entry["id"],
            "TITLE": title,
            "NOTE": desc or f"{title}：这一章只讲一个概念。",
            "LEAD": desc or "一句话说明这一章解决什么问题，再放图。",
            "LANGATTR": "zh-CN" if lang == "zh" else "en",
        }), encoding="utf-8")

    terms = target / "术语.json"
    if not terms.exists():
        terms.write_text(json.dumps({"title": f"{args.title} 术语", "terms": []},
                                    ensure_ascii=False, indent=2) + "\n", encoding="utf-8")

    subprocess.run([sys.executable, str(HERE / "build_terms.py"), str(terms)],
                   check=False, stdout=subprocess.DEVNULL)

    print(f"created {target}")
    for entry in data:
        print(f"  {entry['num']}  {entry['title']:<24} {entry['file']}")
    print(i18n.t("index_written", lang, path=target / "index.html", count=len(data))) if lang == "zh" else print("next: fill each chapter's S array, then open index.html (file://)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
